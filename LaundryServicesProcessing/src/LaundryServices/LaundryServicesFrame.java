    static class LaundryOrder {
    String transactionID;
    String customerName;
    double weight;
    String status;

    LaundryOrder(String transactionID,
                 String customerName,
                 double weight) {

        this.transactionID = transactionID;
        this.customerName = customerName;
        this.weight = weight;
        this.status = "Pending";
    }
}
    LaundryOrder[] queue = new LaundryOrder[100];

    int front = 0;
    int rear = -1;
    int count = 0;

    // Stores all orders for searching
    LaundryOrder[] records = new LaundryOrder[100];
    int totalRecords = 0;

    int transactionNumber = 1001;

     void registerOrder(LaundryOrder order) {

        if (count == queue.length ||
            totalRecords == records.length) {

            javax.swing.JOptionPane.showMessageDialog(
                this, "Laundry queue is full!"
            );

            return;
        }

        rear = (rear + 1) % queue.length;
        queue[rear] = order;
        count++;

        records[totalRecords] = order;
        totalRecords++;

        javax.swing.JOptionPane.showMessageDialog(
            this, "Laundry order registered!\n"
            + "Transaction ID: " + order.transactionID
        );
    }
     
     void displayPending() {

    if (count == 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "No pending laundry orders."
        );
        return;
        }
      String result = "PENDING LAUNDRY ORDERS\n\n";

    for (int i = 0; i < count; i++) {

        int index = (front + i) % queue.length;

        LaundryOrder order = queue[index];

        result += "Transaction ID: "
                + order.transactionID + "\n";

        result += "Customer Name: "
                + order.customerName + "\n";

        result += "Weight: "
                + order.weight + " kg\n";

        result += "Status: "
                + order.status + "\n";

        result += "----------------------\n";
    }

    javax.swing.JOptionPane.showMessageDialog(
        this, result
    );
}  
     
     void processNext() {

        if (count == 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "No laundry orders to process."
            );
            return;
        }

        LaundryOrder order = queue[front];

        queue[front] = null;

        front = (front + 1) % queue.length;

        count--;

        order.status = "Completed";

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Laundry order processed!\n"
            + "Transaction ID: " + order.transactionID
            + "\nCustomer: " + order.customerName
        );
    }
        void searchTransaction(String id) {

    for (int i = 0; i < totalRecords; i++) {

        if (records[i].transactionID
                .equalsIgnoreCase(id)) {

            LaundryOrder order = records[i];
        
     
   
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "TRANSACTION FOUND!\n\n"
                + "Transaction ID: " + order.transactionID
                + "\nCustomer Name: " + order.customerName
                + "\nWeight: " + order.weight + " kg"
                + "\nStatus: " + order.status
            );

            return;
        }
    }
        
            javax.swing.JOptionPane.showMessageDialog(
        this, "Transaction ID not found."
    );
}

